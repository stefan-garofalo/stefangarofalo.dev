function buildOpenCodeConfig(existingConfig, { hasFormatHook }) {
  const config = { ...existingConfig };
  const formatter =
    typeof config.formatter === "object" && config.formatter !== null
      ? { ...config.formatter }
      : {};
  delete formatter["harness-format-edited-file"];

  if (hasFormatHook) {
    formatter["harness-format-edited-file"] = {
      command: ["node", ".agents/hooks/format-edited-file.mjs", "files", "$FILE"],
      extensions: [".js", ".jsx", ".ts", ".tsx", ".mjs", ".cjs", ".json", ".py"],
    };
  }
  if (Object.keys(formatter).length > 0) {
    config.formatter = formatter;
  } else {
    delete config.formatter;
  }

  return {
    $schema: "https://opencode.ai/config.json",
    ...config,
  };
}

async function readJsonFile(filePath) {
  try {
    return JSON.parse(await readFile(filePath, "utf8"));
  } catch (error) {
    if (error && typeof error === "object" && "code" in error && error.code === "ENOENT") {
      return {};
    }
    throw error;
  }
}

