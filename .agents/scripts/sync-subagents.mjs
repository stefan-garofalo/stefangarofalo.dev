const isPathWithin = (root, candidate) => {
  const relative = path.relative(root, candidate);
  return (
    relative === "" ||
    (!relative.startsWith(`..${path.sep}`) && relative !== ".." && !path.isAbsolute(relative))
  );
};

const resolveActionPath = (value, field) => {
  if (typeof value !== "string") {
    throw new Error(`Harness action ${field} path must be a string`);
  }
  const candidate = value.split("#", 1)[0];
  const portableCandidate = candidate.replaceAll("\\", "/");
  if (
    candidate.length === 0 ||
    path.isAbsolute(candidate) ||
    path.win32.isAbsolute(candidate) ||
    portableCandidate.split("/").includes("..")
  ) {
    throw new Error(`Harness action ${field} path escapes the repository: ${value}`);
  }
  const resolved = path.resolve(repoRoot, portableCandidate);
  const relative = path.relative(repoRoot, resolved);
  if (relative === ".." || relative.startsWith(`..${path.sep}`) || path.isAbsolute(relative)) {
    throw new Error(`Harness action ${field} path escapes the repository: ${value}`);
  }
  return resolved;
};

const resolveActionPaths = (action) =>
  Object.fromEntries(
    [
      ...actionPathFields.flatMap((field) => {
        const value = actionPathValue(action, field);
        return value === undefined ? [] : [[field, value]];
      }),
      ...(action.managedHookFiles ?? []).map((value, index) => [
        `managedHookFiles[${index}]`,
        value,
      ]),
    ].map(([field, value]) => [field, resolveActionPath(value, field)]),
  );

const hasInvalidActionPaths = (action) => {
  try {
    resolveActionPaths(action);
    return false;
  } catch {
    return true;
  }
};

async function nearestExistingPath(candidate) {
  let current = candidate;
  while (!(await pathExists(current))) {
    const parent = path.dirname(current);
    if (parent === current) {
      break;
    }
    current = parent;
  }
  return current;
}

async function assertRealPathContainment(action, actionPaths) {
  const realRepoRoot = await realpath(repoRoot);
  for (const [field, candidate] of Object.entries(actionPaths)) {
    const ancestor = await nearestExistingPath(candidate);
    const realAncestor = await realpath(ancestor);
    if (!isPathWithin(realRepoRoot, realAncestor)) {
      throw new Error(
        `Harness action ${field} path escapes the repository: ${actionPathValue(action, field)}`,
      );
    }
  }
}

async function writeAdapterConfig(adapterId, availableHooks) {
  if (adapterId === "codex") {
    await mkdir(path.dirname(codexConfigPath), { recursive: true });
    await writeFile(codexConfigPath, buildCodexAgentConfig(availableHooks), "utf8");
    await rm(path.join(codexDir, "hooks.json"), { force: true });
    return;
  }
  if (adapterId === "claude") {
    await mkdir(path.dirname(claudeSettingsPath), { recursive: true });
    await writeFile(
      claudeSettingsPath,
      encodeJson(buildClaudeSettingsConfig(await readJsonFile(claudeSettingsPath), availableHooks)),
      "utf8",
    );
    return;
  }
  if (adapterId === "cursor") {
    await mkdir(path.dirname(cursorHooksJsonPath), { recursive: true });
    await writeFile(
      cursorHooksJsonPath,
      encodeJson(buildCursorHooksConfig(availableHooks)),
      "utf8",
    );
    return;
  }
  if (adapterId === "opencode") {
    await writeFile(
      opencodeConfigPath,
      encodeOpenCodeConfig(
        buildOpenCodeConfig(await readJsonFile(opencodeConfigPath), availableHooks),
      ),
      "utf8",
    );
  }
}

const hookIdForAction = (action) =>
  action.id.includes(":lifecycle-hook:") ? action.trace?.contribution?.id : undefined;

async function reconcileLifecycleHooks(action, adapterId, actionPaths) {
  const activeHookIds = new Set();
  for (const hookId of action.hookIds) {
    if (await pathExists(path.join(sharedHooksPath, `${hookId}.mjs`))) {
      activeHookIds.add(hookId);
    }
  }
  for (const [index, managedHookFile] of action.managedHookFiles.entries()) {
    const hookId = path.basename(managedHookFile, ".mjs");
    if (!activeHookIds.has(hookId)) {
      await rm(actionPaths[`managedHookFiles[${index}]`], { force: true, recursive: true });
    }
  }
  const projectedHooks = {
    hasFormatHook: action.configurations.some(
      (configuration) =>
        hookIdForAction(configuration) === "format-edited-file" &&
        activeHookIds.has("format-edited-file"),
    ),
    hasUpdateCheckHook: action.configurations.some(
      (configuration) =>
        hookIdForAction(configuration) === "scaffold-update-check" &&
        activeHookIds.has("scaffold-update-check"),
    ),
  };
  if (
    adapterId !== "opencode" ||
    projectedHooks.hasFormatHook ||
    (await pathExists(opencodeConfigPath))
  ) {
    await writeAdapterConfig(adapterId, projectedHooks);
  }
}

async function applyHarnessAction(action, application) {
  const actionPaths = resolveActionPaths(action);
  await assertRealPathContainment(action, actionPaths);
  const adapterId = action.trace.adapter.id;

  if (action.operation === "cleanup-managed-agents") {
    await writeManagedFiles(
      actionPaths.directory,
      action.extension,
      application.rendered[adapterId],
      false,
    );
    return;
  }
  if (action.operation === "reconcile-lifecycle-hooks") {
    await reconcileLifecycleHooks(action, adapterId, actionPaths);
    return;
  }
  if (action.operation === "use-native-mirror") {
    await syncSkillMirrors();
    return;
  }
  if (
    action.operation === "use-native-skill" ||
    action.operation === "use-native-prompt" ||
    action.operation === "native"
  ) {
    return;
  }
  if (action.operation === "mirror") {
    if (action.source !== action.target) {
      const sourcePath = actionPaths.source;
      const targetPath = actionPaths.target;
      if (!(await pathExists(sourcePath))) {
        throw new Error(`Missing canonical source: ${action.source}`);
      }
      if (await pathExists(targetPath)) {
        const targetStat = await lstat(targetPath);
        if (!targetStat.isSymbolicLink() && action.id.includes(":scoped-prompt:")) {
          throw new Error(
            `Consumer prompt target requires explicit preservation: ${action.target}`,
          );
        }
      }
      await ensureSymlink(targetPath, sourcePath);
    }
    return;
  }
  if (action.operation === "merge-json" || action.operation === "merge-toml") {
    return;
  }
  if (action.operation === "render-template" || action.operation === "render") {
    const name = action.templateId ?? action.contributionId;
    const content = application.rendered[adapterId]?.[name];
    const target = actionTargetPath(action);
    if (typeof content !== "string" || target === undefined) {
      throw new Error(`Missing ${adapterId} render input for ${name ?? "unknown template"}`);
    }
    const targetPath = resolveActionPath(target, "target");
    await mkdir(path.dirname(targetPath), { recursive: true });
    await writeFile(targetPath, content, "utf8");
    return;
  }

  throw new Error(`Unknown harness application operation: ${action.operation}`);
}

async function cleanupManagedAgents(application, writeCurrent = false) {
  for (const [adapterId, surface] of Object.entries(harnessAgentSurface)) {
    const rendered = application.rendered[adapterId];
    await writeManagedFiles(surface.directory, surface.extension, rendered, writeCurrent);
  }
}

async function materializeLegacyHarnesses(application) {
  await writeAdapterConfig("codex", application.availableHooks);
  await writeAdapterConfig("claude", application.availableHooks);
  await writeAdapterConfig("cursor", application.availableHooks);
  if (application.availableHooks.hasFormatHook || (await pathExists(opencodeConfigPath))) {
    await writeAdapterConfig("opencode", application.availableHooks);
  }
  await cleanupManagedAgents(application, true);
  await syncPromptMirrors();
  await syncSkillMirrors();
  await syncHookSurface();
}

const summaryState = (summary) =>
  summary._tag === "HarnessProjectionFailure"
    ? {
        applied: summary.completed,
        omissions: summary.omissions,
        failures: summary.errors,
      }
    : {
        applied: summary.applied,
        omissions: summary._tag === "HarnessProjectionPartial" ? summary.omissions : [],
        failures: [],
      };

const projectionEvidence = ({ adapter, projection, summary }) => {
  const state = summaryState(summary);
  return {
    adapter: adapter.matrix.adapter,
    matrixVersion: adapter.matrix.matrixVersion,
    actions: projection.actions,
    warnings: [
      ...state.applied
        .filter(({ support }) => support === "degraded")
        .map(({ reason, trace }) => ({
          _tag: "DegradedHarnessCapabilityWarning",
          reason,
          trace,
        })),
      ...state.omissions.map(({ warning, trace }) => ({ ...warning, trace })),
    ],
    omissions: state.omissions,
    failures: state.failures,
  };
};

const receiptStatus = (projections) =>
  projections.some(({ failures }) => failures.length > 0)
    ? "failure"
    : projections.some(({ warnings, omissions }) => warnings.length > 0 || omissions.length > 0)
      ? "partial"
      : "success";

const projectSafely = (adapter, contextPlan) => {
  try {
    const issue = canonicalContextIssue(contextPlan);
    if (issue !== undefined) {
      throw new Error(issue);
    }
    return project({ adapter, contextPlan });
  } catch (error) {
    return {
      actions: [],
      summary: {
        _tag: "HarnessProjectionFailure",
        completed: [],
        omissions: [],
        errors: [
          {
            _tag: "InvalidHarnessProjectionError",
            trace: {
              contextPlanVersion: contextPlanVersion(contextPlan),
              scopeId: "unknown",
              contribution: { id: "context-plan", version: "unknown" },
              adapter: adapter.matrix.adapter,
              matrixVersion: adapter.matrix.matrixVersion,
            },
            message: error instanceof Error ? error.message : "Invalid canonical context plan",
          },
        ],
      },
    };
  }
};

