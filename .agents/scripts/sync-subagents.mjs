function isObject(value) {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function removeClaudeHookCommand(entries, command) {
  if (!Array.isArray(entries)) {
    return [];
  }

  return entries.flatMap((entry) => {
    if (!isObject(entry) || !Array.isArray(entry.hooks)) {
      return [entry];
    }

    const hooks = entry.hooks.filter((hook) => !isObject(hook) || hook.command !== command);
    return hooks.length === 0 ? [] : [{ ...entry, hooks }];
  });
}

function setClaudeHookEntries(hooks, key, entries) {
  if (entries.length > 0) {
    hooks[key] = entries;
  } else {
    delete hooks[key];
  }
}

function buildClaudeSettingsConfig(existingConfig, { hasFormatHook, hasUpdateCheckHook }) {
  const config = isObject(existingConfig) ? existingConfig : {};
  const existingHooks = isObject(config.hooks) ? config.hooks : {};
  const hooks = { ...existingHooks };
  const sessionStartHooks = removeClaudeHookCommand(
    existingHooks.SessionStart,
    claudeUpdateCheckCommand,
  );
  const postToolUseHooks = removeClaudeHookCommand(existingHooks.PostToolUse, claudeFormatCommand);

  if (hasUpdateCheckHook) {
    hooks.SessionStart = [
      ...sessionStartHooks,
      {
        hooks: [
          {
            type: "command",
            command: claudeUpdateCheckCommand,
            timeout: 60,
          },
        ],
      },
    ];
  } else {
    setClaudeHookEntries(hooks, "SessionStart", sessionStartHooks);
  }

  if (hasFormatHook) {
    hooks.PostToolUse = [
      ...postToolUseHooks,
      {
        matcher: "Edit|Write|MultiEdit",
        hooks: [
          {
            type: "command",
            command: claudeFormatCommand,
            timeout: 30,
          },
        ],
      },
    ];
  } else {
    setClaudeHookEntries(hooks, "PostToolUse", postToolUseHooks);
  }

  return {
    ...config,
    hooks,
  };
}

